    fun getPhrase(emotion: MascotEmotion, streak: Int = 0): String {
        return getPhrase(MascotType.getRandom(), emotion, streak)
    }

    fun getPhrase(mascotType: MascotType, emotion: MascotEmotion, streak: Int = 0): String {
        val pool = when (mascotType) {
            MascotType.SIB_GUTENOK -> when (emotion) {
                MascotEmotion.ON_FIRE -> DUCK_ON_FIRE
                MascotEmotion.PROUD -> DUCK_PROUD
                MascotEmotion.WATCHFUL -> DUCK_WATCHFUL
                MascotEmotion.SAD -> DUCK_SAD
                MascotEmotion.UNHINGED -> DUCK_UNHINGED
                MascotEmotion.GHOST -> DUCK_GHOST
                MascotEmotion.DOOM -> DUCK_DOOM
            }
            MascotType.SQUIRREL_COMM -> when (emotion) {
                MascotEmotion.ON_FIRE -> SQUIRREL_ON_FIRE
                MascotEmotion.PROUD -> SQUIRREL_PROUD
                MascotEmotion.WATCHFUL -> SQUIRREL_WATCHFUL
                MascotEmotion.SAD -> SQUIRREL_SAD
                MascotEmotion.UNHINGED -> SQUIRREL_UNHINGED
                MascotEmotion.GHOST -> SQUIRREL_GHOST
                MascotEmotion.DOOM -> SQUIRREL_DOOM
            }
        }
        val template = pool[Random.nextInt(pool.size)]
        return if (template.contains("%d")) {
            String.format(template, maxOf(1, streak))
        } else {
            template
        }
    }

